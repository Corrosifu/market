from decimal import Decimal
from typing import Protocol

from market_order.domain.models import Line, PaymentOutcome, Reason, Reply, Saga, Step


class Publisher(Protocol):
    async def send(self, order_id: str, event: dict[str, object]) -> None: ...


class Orders(Protocol):
    async def begin(
        self, customer_id: str, key: str, lines: tuple[Line, ...], total: Decimal, simulate_failure: bool
    ) -> Saga | Reply: ...
    async def checkpoint(
        self, saga: Saga, step: Step, reason: Reason | None = None, code: int | None = None
    ) -> None: ...
    async def remember(self, saga: Saga, reply: Reply) -> None: ...
    async def finish(self, saga: Saga, confirmed: bool, reason: Reason | None, reply: Reply) -> None: ...
    async def get(self, order_id: str, customer_id: str, ops: bool) -> dict[str, object] | None: ...
    async def claim_stale(self, seconds: float, active: set[str]) -> Saga | None: ...
    async def ready(self) -> bool: ...


class Inventory(Protocol):
    async def reserve(self, saga: Saga) -> bool: ...
    async def confirm(self, saga: Saga) -> bool: ...
    async def release(self, saga: Saga) -> bool: ...


class Payment(Protocol):
    async def pay(self, saga: Saga) -> PaymentOutcome: ...
